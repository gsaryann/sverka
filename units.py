def parse_unit(u: str) -> Tuple[Optional[str], float]:
    """Разбирает строку единицы измерения.
    
    Примеры:
      '100 м2' -> ('area', 100.0)
      '100 пог. м' -> ('length', 100.0)
      '0.8 10 м' -> ('length', 8.0)
      '1т груза' -> ('mass', 1000.0)
      'шт' -> ('count', 1.0)
      'неизвестное' -> ('неизвестное', 1.0)
    """
    if not u or not isinstance(u, str):
        return None, 1.0
    
    s = u.lower().strip().replace(',', '.').replace('ё', 'е')
    s = re.sub(r'\s+', ' ', s)

    # Выделяем ведущий числовой коэффициент, например "100 м2", "1000 шт", "0.1 т"
    mult = 1.0
    m_num = re.match(r'^(\d+(?:\.\d+)?)\s*(.*)$', s)
    rest = s
    if m_num:
        mult = float(m_num.group(1))
        rest = m_num.group(2).strip()

    if not rest:
        return 'count', mult

    # Проверяем точное совпадение остатка в словаре
    if rest in _CANONICAL_MAP:
        dim, k = _CANONICAL_MAP[rest]
        return dim, mult * k

    # Пытаемся найти составные формы ("пог. м", "куб. м", "кв. м") в начале остатка
    # Сортируем ключи по убыванию длины, чтобы более длинные сочетания матчились первыми
    for key, (dim, k) in sorted(_CANONICAL_MAP.items(), key=lambda x: len(x[0]), reverse=True):
        if rest.startswith(key):
            # Проверяем, что после совпадения идет пробел, точка или конец строки
            tail = rest[len(key):]
            if not tail or tail[0] in ' .':
                return dim, mult * k

    # Первое слово остатка
    first_word = rest.split()[0].rstrip('.,;')
    if first_word in _CANONICAL_MAP:
        dim, k = _CANONICAL_MAP[first_word]
        return dim, mult * k

    # Если неизвестная строительная единица (например: стыков, проемов, гибов)
    # возвращаем первое значащее слово как размерность
    return first_word, mult


def to_base(qty: Optional[float], unit: str) -> Tuple[Optional[str], Optional[float]]:
    """Переводит количество в базовую единицу своей размерности."""
    if qty is None:
        return None, None
    dim, k = parse_unit(unit)
    if dim is None:
        return None, None
    return dim, float(qty) * k
